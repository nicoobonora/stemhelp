export function translate(key:string, language:AppLanguage, values:Record<string,string|number>={}):string {
  const text=language==='it'?key:(english[key]??key);
  return text.replace(/\{(\d+)\}/g,(match,index)=>Object.hasOwn(values,index)?String(values[index]):match);
}

// Only use for application-owned status/error messages, never for course text.
const patterns=Object.entries(english).filter(([key])=>/\{\d+\}/.test(key)).map(([key,value])=>{
  const indices:string[]=[];
  const pattern=key.split(/(\{\d+\})/).map(part=>{
    if(/^\{\d+\}$/.test(part)){indices.push(part.slice(1,-1));return '([\\s\\S]*?)';}
    return part.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
  }).join('');
  return {pattern:new RegExp('^'+pattern+'$'),indices,value};
});
export function translateMessage(message:string,language:AppLanguage):string{
  if(language==='it')return message;
  if(english[message])return english[message];
  for(const {pattern,indices,value} of patterns){const match=message.match(pattern);if(match){const values=Object.fromEntries(indices.map((index,i)=>[index,match[i+1]]));return value.replace(/\{(\d+)\}/g,(_,index)=>values[index]);}}
  return message;
}
